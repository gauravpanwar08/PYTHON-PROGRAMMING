-- ARITHMETIC OPERATORS (+, -, *, /, %)

SELECT STUDENT_NAME,
       HINDI + ENGLISH + MATHS + PHYSICS + CHEMISTRY AS TOTAL_MARKS
FROM STUDENT_MARKS;

SELECT STUDENT_NAME,
       (HINDI + ENGLISH + MATHS + PHYSICS + CHEMISTRY) / 5 AS AVERAGE_MARKS
FROM STUDENT_MARKS;

SELECT STUDENT_NAME, SCHOLARSHIP, (SCHOLARSHIP * 1.10) AS NEW_SCHOLARSHIP
FROM STUDENT_MARKS;

-- COMPARISON OPERATORS (=, <, >, <=, >=, != or <>)

SELECT *FROM STUDENT_MARKS
WHERE STUDENT_NAME = 'NEHA SHARMA';

SELECT *FROM STUDENT_MARKS
WHERE ENGLISH <> 65;            -- != OR <>

SELECT *FROM STUDENT_MARKS
WHERE ENGLISH > 80;

SELECT *FROM STUDENT_MARKS
WHERE ENGLISH < 80;

SELECT *FROM STUDENT_MARKS
WHERE CHEMISTRY >= 90;

SELECT *FROM STUDENT_MARKS
WHERE CHEMISTRY <= 70;

-- LOGICAL OPERATORS (AND,OR,NOT)

SELECT *FROM STUDENT_MARKS
WHERE PHYSICS >= 90 AND PHYSICS <= 95;

SELECT *FROM STUDENT_MARKS
WHERE PHYSICS <= 70 OR MATHS <= 70;

SELECT * FROM STUDENT_MARKS 
WHERE SCHOLARSHIP > 5000 OR ATTENDANCE > 95;

SELECT *FROM STUDENT_MARKS
WHERE NOT HINDI <= 75;

SELECT * FROM STUDENT_MARKS 
WHERE NOT CITY = 'DELHI';

-- BETWEEN OPERATOR (RANGE FROM X TO Y)

SELECT * FROM STUDENT_MARKS WHERE PHYSICS BETWEEN 70 AND 90;
SELECT * FROM STUDENT_MARKS WHERE SCHOLARSHIP BETWEEN 2000 AND 6000;

-- IN Operator

SELECT * FROM STUDENT_MARKS WHERE CITY IN ('DELHI', 'MUMBAI');
SELECT * FROM STUDENT_MARKS WHERE STUDENT_NAME IN ('NEHA SHARMA','PRIYA SINGH','ANITA MEHTA');

-- LIKE OPERATOR

SELECT * FROM STUDENT_MARKS WHERE STUDENT_NAME LIKE 'G%';      -- STARTS WITH G
SELECT * FROM STUDENT_MARKS WHERE STUDENT_NAME LIKE '%RA%';	   -- RA IN MIDDLE
SELECT * FROM STUDENT_MARKS WHERE STUDENT_NAME LIKE '%A';      -- ENDS WITH A

-- IS NULL / IS NOT NULL OPERATOR

SELECT * FROM STUDENT_MARKS WHERE SCHOLARSHIP IS NULL;
SELECT * FROM STUDENT_MARKS WHERE SCHOLARSHIP IS NOT NULL;

-- ORDER BY CLAUSE (Ascending / Descending)

SELECT * FROM STUDENT_MARKS ORDER BY STUDENT_NAME ASC;            -- A TO Z

SELECT * FROM STUDENT_MARKS ORDER BY STUDENT_NAME DESC;             -- Z TO A

SELECT STUDENT_NAME, MATHS FROM STUDENT_MARKS ORDER BY MATHS DESC;    -- HIGH TO LOW

SELECT STUDENT_NAME, ENGLISH FROM STUDENT_MARKS ORDER BY ENGLISH ASC;   -- LOW TO HIGH

-- LIMIT CLAUSE (Top-N Records)

SELECT STUDENT_NAME, CHEMISTRY 
FROM STUDENT_MARKS 
ORDER BY MATHS DESC 
LIMIT 3;

SELECT * FROM STUDENT_MARKS LIMIT 2;       -- show starting 2 records

SELECT * FROM STUDENT_MARKS LIMIT 2, 3;    -- show 3 records after skip starting 2 records
