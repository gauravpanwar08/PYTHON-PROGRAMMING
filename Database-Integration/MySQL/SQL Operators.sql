CREATE DATABASE STUDENT;
USE STUDENT;

CREATE TABLE STUDENT_MARKS(
    ROLL_NO INT PRIMARY KEY,
    STUDENT_NAME VARCHAR(50),
    HINDI INT,
    ENGLISH INT,
    MATHS INT,
    PHYSICS INT,
    CHEMISTRY INT,
    AGE INT,                     -- comparison operator use के लिए
    GENDER VARCHAR(10),          -- IN / NOT IN / LIKE के लिए
    CITY VARCHAR(50),            -- LIKE / pattern match
    SCHOLARSHIP DECIMAL(10,2),   -- arithmetic, >, <, BETWEEN
    ATTENDANCE INT               -- % attendance check करने के लिए
);

